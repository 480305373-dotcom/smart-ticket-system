CREATE TABLE IF NOT EXISTS knowledge_article (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(200) NOT NULL, summary VARCHAR(500) NOT NULL, content TEXT NOT NULL,
 category VARCHAR(100) NOT NULL, keywords VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('DRAFT','PUBLISHED')),
 created_by BIGINT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_knowledge_status_category ON knowledge_article(status,category);
