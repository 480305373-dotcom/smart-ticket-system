-- Additive migration: existing rows and tables are preserved.
CREATE TABLE IF NOT EXISTS app_user (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, username VARCHAR(100) UNIQUE NOT NULL,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(50) NOT NULL DEFAULT 'USER');
CREATE TABLE IF NOT EXISTS ticket (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, title VARCHAR(200) NOT NULL,
 description TEXT, priority INTEGER NOT NULL DEFAULT 3 CHECK (priority BETWEEN 1 AND 5),
 status VARCHAR(50) NOT NULL DEFAULT 'OPEN', user_id BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
ALTER TABLE ticket ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE ticket ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
CREATE TABLE IF NOT EXISTS operation_log (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, user_id BIGINT REFERENCES app_user(id),
 action VARCHAR(100) NOT NULL, target_type VARCHAR(100), target_id BIGINT, detail TEXT,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS ticket_comment (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES app_user(id), content TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS ticket_history (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, ticket_id BIGINT NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
 operator_id BIGINT NOT NULL REFERENCES app_user(id), action VARCHAR(100) NOT NULL,
 old_status VARCHAR(50), new_status VARCHAR(50), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS knowledge_article (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, title VARCHAR(200) NOT NULL, summary VARCHAR(500) NOT NULL,
 content TEXT NOT NULL, category VARCHAR(100) NOT NULL, keywords VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED')), created_by BIGINT NOT NULL REFERENCES app_user(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS token_blacklist (
 token_hash VARCHAR(64) PRIMARY KEY, expires_at TIMESTAMP NOT NULL);
CREATE TABLE IF NOT EXISTS demo_seed (
 seed_key VARCHAR(100) PRIMARY KEY, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_ticket_user_status ON ticket(user_id, status);
CREATE INDEX IF NOT EXISTS idx_ticket_comment_time ON ticket_comment(ticket_id, created_at);
CREATE INDEX IF NOT EXISTS idx_ticket_history_time ON ticket_history(ticket_id, created_at);
CREATE INDEX IF NOT EXISTS idx_knowledge_status_category ON knowledge_article(status, category);

-- Ticket assignment and durable normal-create idempotency (v2).
ALTER TABLE ticket ADD COLUMN IF NOT EXISTS assignee_id BIGINT REFERENCES app_user(id);
ALTER TABLE ticket_history ADD COLUMN IF NOT EXISTS old_assignee_id BIGINT REFERENCES app_user(id);
ALTER TABLE ticket_history ADD COLUMN IF NOT EXISTS new_assignee_id BIGINT REFERENCES app_user(id);
CREATE INDEX IF NOT EXISTS idx_ticket_assignee_status ON ticket(assignee_id,status);
CREATE TABLE IF NOT EXISTS ticket_request (
 user_id BIGINT NOT NULL REFERENCES app_user(id), request_id VARCHAR(100) NOT NULL,
 fingerprint VARCHAR(64) NOT NULL, ticket_id BIGINT REFERENCES ticket(id) ON DELETE SET NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,request_id));

-- v3: durable event delivery, consumer inbox, account session invalidation.
CREATE TABLE IF NOT EXISTS event_outbox (
 event_id VARCHAR(100) PRIMARY KEY, payload TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','SENT','FAILED')),
 attempts INTEGER NOT NULL DEFAULT 0, next_attempt_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 locked_until TIMESTAMP, lock_token VARCHAR(100), last_error VARCHAR(200),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, sent_at TIMESTAMP);
CREATE INDEX IF NOT EXISTS idx_outbox_pending ON event_outbox(next_attempt_at) WHERE status='PENDING';
CREATE TABLE IF NOT EXISTS processed_message (
 event_id VARCHAR(100) PRIMARY KEY, processed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE app_user ADD COLUMN IF NOT EXISTS auth_version INTEGER NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS idx_token_blacklist_expiry ON token_blacklist(expires_at);
CREATE INDEX IF NOT EXISTS idx_operation_log_time ON operation_log(created_at DESC);
CREATE TABLE IF NOT EXISTS knowledge_vector_index (
 article_id BIGINT PRIMARY KEY REFERENCES knowledge_article(id) ON DELETE CASCADE,
 fingerprint VARCHAR(64) NOT NULL, indexed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP);
